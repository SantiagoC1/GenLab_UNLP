"""Storage of the extraction labs and of the booked appointments.

Only booked appointments are stored: the free ones are generated by the rule in `reglas.py`.

TODO: swap the in-memory implementations for ones backed by the tables `extraction_labs` and
`appointments` (the unique index `appointments_one_per_slot` is what guarantees "one person per
slot" there) without touching the service or the router.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass
from datetime import datetime, timedelta

PROGRAMADO = "Programado"
CANCELADO = "Cancelado"
AUSENTE = "Ausente"
REALIZADO = "Realizado"


class TurnoOcupado(Exception):
    """The slot was taken by someone else before it was booked."""


@dataclass(frozen=True)
class Laboratorio:
    id: int
    nombre: str
    direccion: str
    provincia: str
    latitud: float
    longitud: float


@dataclass
class Recordatorio:
    """The e-mail reminder that is scheduled with every appointment."""

    enviar_en: datetime
    canal: str = "email"
    anulado: bool = False


@dataclass(frozen=True)
class Muestra:
    """A blood sample reported by the extraction lab. Every one is kept (table `samples`)."""

    id: int
    estudio_id: int
    volumen_ml: float
    tomada_en: datetime


@dataclass
class Remuestreo:
    """A new sample is needed for the same study, at no cost (M6-RF10)."""

    id: int
    estudio_id: int
    motivo: str
    detalle: str
    registrado_en: datetime
    resuelto: bool = False  # True once the patient books the new appointment


@dataclass
class Turno:
    id: int
    estudio_id: int
    laboratorio_id: int
    inicio: datetime
    estado: str
    creado_en: datetime
    recordatorio: Recordatorio


class RepositorioTurnos(ABC):
    @abstractmethod
    def listar_laboratorios(self, provincia: str | None = None) -> list[Laboratorio]: ...

    @abstractmethod
    def obtener_laboratorio(self, laboratorio_id: int) -> Laboratorio | None: ...

    @abstractmethod
    def ocupados(self, laboratorio_id: int, desde: datetime, hasta: datetime) -> set[datetime]:
        """Inicios de los turnos no cancelados del laboratorio entre las dos fechas."""

    @abstractmethod
    def crear_turno(
        self,
        estudio_id: int,
        laboratorio_id: int,
        inicio: datetime,
        creado_en: datetime,
        recordatorio: Recordatorio,
    ) -> Turno:
        """Reserva el turno. Lanza `TurnoOcupado` si ya lo tomó otra persona."""

    @abstractmethod
    def obtener_turno(self, turno_id: int) -> Turno | None: ...

    @abstractmethod
    def marcar_turno(self, turno_id: int, estado: str, anular_recordatorio: bool = False) -> Turno:
        """Cambia el estado del turno; al cancelarlo se anula también su recordatorio."""

    @abstractmethod
    def turno_vigente_de_estudio(self, estudio_id: int) -> Turno | None:
        """El turno Programado del estudio, si tiene uno."""

    @abstractmethod
    def registrar_muestra(
        self, estudio_id: int, volumen_ml: float, tomada_en: datetime
    ) -> Muestra: ...

    @abstractmethod
    def listar_muestras(self, estudio_id: int) -> list[Muestra]:
        """Las muestras del estudio, de la primera a la última."""

    @abstractmethod
    def registrar_remuestreo(
        self, estudio_id: int, motivo: str, detalle: str, registrado_en: datetime
    ) -> Remuestreo: ...

    @abstractmethod
    def remuestreo_pendiente(self, estudio_id: int) -> Remuestreo | None:
        """El remuestreo del estudio al que el paciente todavía no le sacó turno."""

    @abstractmethod
    def resolver_remuestreo(self, estudio_id: int) -> None: ...

    @abstractmethod
    def listar_programados(self) -> list[Turno]:
        """Los turnos Programados de todos los laboratorios, del más próximo al más lejano."""

    @abstractmethod
    def contar_inasistencias(self, estudio_id: int) -> int:
        """Cuántos turnos del estudio se registraron como Ausente."""

    @abstractmethod
    def listar_de_estudios(self, estudio_ids: list[int]) -> list[Turno]:
        """Todos los turnos de esos estudios, del más reciente al más antiguo."""


# Approximate center of each province: the labs are spread around it.
